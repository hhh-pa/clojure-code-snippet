// Package aot ahead-of-time compiles snippet scripts to JVM bytecode
// so snip measure --aot can measure the compiled run with the same
// harness as script mode. Each script becomes a generated gen-class
// namespace (definitions kept verbatim, action forms moved into an
// entry point), compiled once into a content-hash cache and rerun
// from classes on every later use.
package aot

import (
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/hhh-pa/clojure/scripts/ci/go/internal/cljread"
	"github.com/hhh-pa/clojure/scripts/ci/go/internal/snipcore"
)

// defHeads are top-level heads kept verbatim at load position.
var defHeads = map[string]bool{
	"def": true, "defn": true, "defn-": true, "defmacro": true,
	"defmulti": true, "defmethod": true, "defprotocol": true,
	"defrecord": true, "deftype": true, "declare": true,
	"require": true, "use": true, "import": true, "comment": true,
}

// Built is one compiled snippet, ready to run from classes.
type Built struct {
	NS         string // Clojure namespace name
	Class      string // binary class name (munged)
	ClassesDir string // classes directory (cache hit or fresh)
	Cached     bool   // true when the compile was skipped on cache hit
}

// Argv returns the run command: java -cp <classes>:<cp> <class>.
func (b *Built) Argv(classpath string) []string {
	return []string{"java", "-cp", b.ClassesDir + string(os.PathListSeparator) + classpath, b.Class}
}

// TransformResult is the generated namespace source for a script.
type TransformResult struct {
	NS     string // namespace name
	Source string // full generated source
	Class  string // binary class name
}

// Transform converts a script file into a gen-class namespace:
// the original ns form (plus injected :gen-class) or a generated
// one, definitions verbatim, every other top-level form moved into
// -aot-run behind a -main entry point. A script-defined -main is
// renamed to script-main first so the entry point never clashes.
func Transform(scriptPath, label, stem string) (*TransformResult, error) {
	raw, err := os.ReadFile(scriptPath)
	if err != nil {
		return nil, err
	}
	src := string(raw)
	forms, err := cljread.Split(src)
	if err != nil {
		return nil, err
	}
	if definesMain(forms) {
		src = rewriteSymbol(src, "-main", "script-main")
		forms, err = cljread.Split(src)
		if err != nil {
			return nil, err
		}
	}
	var nsForm string
	var kept, actions []string
	for _, form := range forms {
		head := cljread.Head(form)
		switch {
		case head == "ns":
			if nsForm != "" {
				return nil, errors.New("multiple ns forms")
			}
			if strings.Contains(form, "gen-class") {
				return nil, errors.New("ns form already has gen-class")
			}
			nsForm = form
		case head == "in-ns":
			return nil, errors.New("in-ns is not AOT-safe")
		case defHeads[head]:
			kept = append(kept, form)
		default:
			actions = append(actions, form)
		}
	}
	var ns, head string
	if nsForm != "" {
		ns = nsName(nsForm)
		if ns == "" {
			return nil, errors.New("cannot parse ns name")
		}
		head = injectGenClass(nsForm)
	} else {
		ns = genName(label, stem)
		head = "(ns " + ns + " (:gen-class :main true))"
	}
	var sb strings.Builder
	sb.WriteString(";; AOT wrapper generated by snip measure --aot from ")
	sb.WriteString(scriptPath)
	sb.WriteString("; do not edit.\n")
	sb.WriteString(head)
	for _, form := range kept {
		sb.WriteString("\n\n")
		sb.WriteString(form)
	}
	sb.WriteString("\n\n(defn -aot-run []\n")
	for _, form := range actions {
		sb.WriteString("  ")
		sb.WriteString(strings.ReplaceAll(form, "\n", "\n  "))
		sb.WriteString("\n")
	}
	// clojure.main flushes *out* after a script; a bare gen-class
	// entry point would drop a trailing print without newline.
	sb.WriteString(")\n\n(defn -main [& _args]\n  (try (-aot-run) (finally (flush))))\n")
	return &TransformResult{NS: ns, Source: sb.String(), Class: Munge(ns)}, nil
}

// definesMain reports whether any form defines the -main var.
func definesMain(forms []string) bool {
	for _, form := range forms {
		head := cljread.Head(form)
		if head != "defn" && head != "defn-" && head != "def" && head != "defmacro" {
			continue
		}
		if definedName(form) == "-main" {
			return true
		}
	}
	return false
}

// definedName extracts the var name from a def-like form, skipping
// metadata maps/vectors and a docstring is never before the name.
func definedName(form string) string {
	toks := tokenizeHead(form, 6)
	// toks[0] is the head (defn/...); the name is the first
	// following token that is not metadata.
	for _, tok := range toks[1:] {
		if tok == "" {
			continue
		}
		if strings.HasPrefix(tok, "^") || strings.HasPrefix(tok, "{") {
			continue
		}
		return tok
	}
	return ""
}

// tokenizeHead returns the first n raw tokens of a list form.
func tokenizeHead(form string, n int) []string {
	var toks []string
	i := 0
	// Skip the opening paren and head reader prefixes.
	for i < len(form) && (form[i] == '(' || form[i] == '\'' || form[i] == '@' || form[i] == '`' || form[i] == '~') {
		i++
	}
	for i < len(form) && len(toks) < n {
		// Skip whitespace, commas, comments.
		for i < len(form) {
			c := form[i]
			if c == ' ' || c == '\t' || c == '\n' || c == '\r' || c == ',' {
				i++
				continue
			}
			if c == ';' {
				for i < len(form) && form[i] != '\n' {
					i++
				}
				continue
			}
			break
		}
		if i >= len(form) {
			break
		}
		start := i
		c := form[i]
		switch {
		case c == '"':
			i++
			for i < len(form) {
				if form[i] == '\\' {
					i += 2
					continue
				}
				i++
				if form[i-1] == '"' {
					break
				}
			}
		case c == '{' || c == '[' || c == '(':
			depth := 0
			for i < len(form) {
				d := form[i]
				if d == '"' {
					i++
					for i < len(form) {
						if form[i] == '\\' {
							i += 2
							continue
						}
						i++
						if form[i-1] == '"' {
							break
						}
					}
					continue
				}
				if d == '(' || d == '[' || d == '{' {
					depth++
				} else if d == ')' || d == ']' || d == '}' {
					depth--
					if depth == 0 {
						i++
						break
					}
				}
				i++
			}
		default:
			for i < len(form) && isSymChar(form[i]) {
				i++
			}
		}
		toks = append(toks, form[start:i])
	}
	return toks
}

func isSymChar(c byte) bool {
	switch c {
	case ' ', '\t', '\n', '\r', ',', ';', '"', '(', ')', '[', ']', '{', '}':
		return false
	}
	return true
}

// rewriteSymbol renames whole-symbol occurrences outside strings,
// comments, and char literals. Qualified syms (foo/-main) and
// keywords (:main) never match a bare from.
func rewriteSymbol(src, from, to string) string {
	var sb strings.Builder
	sb.Grow(len(src) + 256)
	i := 0
	for i < len(src) {
		c := src[i]
		switch {
		case c == '"':
			start := i
			i++
			for i < len(src) {
				if src[i] == '\\' {
					i += 2
					continue
				}
				i++
				if src[i-1] == '"' {
					break
				}
			}
			sb.WriteString(src[start:i])
		case c == ';':
			start := i
			for i < len(src) && src[i] != '\n' {
				i++
			}
			sb.WriteString(src[start:i])
		case c == '\\' && i+1 < len(src):
			start := i
			i++
			for i < len(src) && isSymChar(src[i]) {
				i++
			}
			sb.WriteString(src[start:i])
		case c == ':' && i+1 < len(src) && isSymChar(src[i+1]) && src[i+1] != ':':
			// Keyword: never a symbol occurrence.
			start := i
			i++
			for i < len(src) && isSymChar(src[i]) {
				i++
			}
			sb.WriteString(src[start:i])
		case isSymChar(c):
			start := i
			for i < len(src) && isSymChar(src[i]) {
				i++
			}
			tok := src[start:i]
			if tok == from {
				sb.WriteString(to)
			} else {
				sb.WriteString(tok)
			}
		default:
			sb.WriteByte(c)
			i++
		}
	}
	return sb.String()
}

// nsName extracts the name from an (ns name ...) form.
func nsName(nsForm string) string {
	toks := tokenizeHead(nsForm, 3)
	if len(toks) < 2 {
		return ""
	}
	return toks[1]
}

// injectGenClass splices (:gen-class :main true) before the final paren.
func injectGenClass(nsForm string) string {
	trimmed := strings.TrimRight(nsForm, " \t\n\r")
	idx := strings.LastIndex(trimmed, ")")
	return trimmed[:idx] + " (:gen-class :main true)" + trimmed[idx:]
}

// genName derives a deterministic namespace from label/stem.
func genName(label, stem string) string {
	sanitized := strings.Map(func(r rune) rune {
		if r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '_' {
			return r
		}
		return '_'
	}, label+"/"+stem)
	return "snip_" + sanitized
}

// mungeReplacements mirrors clojure.lang.Compiler/munge.
var mungeReplacements = map[rune]string{
	'-': "_", ':': "_COLON_", '+': "_PLUS_", '>': "_GT_",
	'<': "_LT_", '=': "_EQ_", '~': "_TILDE_", '!': "_BANG_",
	'@': "_CIRCA_", '#': "_SHARP_", '\'': "_SINGLEQUOTE_",
	'"': "_DOUBLEQUOTE_", '%': "_PERCENT_", '^': "_CARET_",
	'&': "_AMPERSAND_", '*': "_STAR_", '|': "_BAR_",
	'{': "_LBRACE_", '}': "_RBRACE_", '[': "_LBRACK_",
	']': "_RBRACK_", '/': ".", '\\': "_BSLASH_", '?': "_QMARK_",
}

// Munge maps a namespace to its binary class name.
func Munge(ns string) string {
	var sb strings.Builder
	for _, r := range ns {
		if rep, ok := mungeReplacements[r]; ok {
			sb.WriteString(rep)
		} else {
			sb.WriteRune(r)
		}
	}
	return sb.String()
}

// nsFile maps a namespace to its source path (dashes to underscores,
// dots to directories), the way Clojure classpath loading finds it.
func nsFile(ns string) string {
	flat := strings.ReplaceAll(ns, "-", "_")
	return filepath.Join(strings.Split(flat, ".")...) + ".clj"
}

// cljString quotes a path as a Clojure string literal.
func cljString(s string) string {
	r := strings.ReplaceAll(s, "\\", "\\\\")
	return `"` + strings.ReplaceAll(r, `"`, `\"`) + `"`
}

// Compile builds the transformed script into the content-hash cache
// (skipping the compile on marker hit) and returns the runnable
// artifact. cacheDir defaults to <root>/.ci/aot-cache when empty.
func Compile(root, cacheDir, classpath, javaVersion, label, stem, scriptPath string, timeout int) (*Built, error) {
	if cacheDir == "" {
		cacheDir = filepath.Join(root, ".ci", "aot-cache")
	}
	raw, err := os.ReadFile(scriptPath)
	if err != nil {
		return nil, err
	}
	// The key covers the generated namespace too: identical scripts
	// under different labels/stems (a problem dir's solution.clj
	// next to its named twin) compile to different classes and must
	// never share, or race on, one slot.
	h := sha256.New()
	h.Write([]byte(label + "\x00" + stem + "\x00"))
	h.Write(raw)
	key := hex.EncodeToString(h.Sum(nil))
	slot := filepath.Join(cacheDir, key)
	classes := filepath.Join(slot, "classes")
	marker := filepath.Join(slot, "ok")
	wantMarker := "v2\n" + javaVersion + "\n" + classpath + "\n"
	if got, err := os.ReadFile(marker); err == nil && string(got) == wantMarker {
		tr, err := Transform(scriptPath, label, stem)
		if err != nil {
			return nil, err
		}
		if _, err := os.Stat(filepath.Join(classes, classFile(tr.Class))); err == nil {
			return &Built{NS: tr.NS, Class: tr.Class, ClassesDir: classes, Cached: true}, nil
		}
		// Marker hit but classes missing: recompile below.
	}
	tr, err := Transform(scriptPath, label, stem)
	if err != nil {
		return nil, err
	}
	srcDir := filepath.Join(slot, "src")
	if err := os.RemoveAll(slot); err != nil {
		return nil, err
	}
	srcPath := filepath.Join(srcDir, nsFile(tr.NS))
	if err := os.MkdirAll(filepath.Dir(srcPath), 0o755); err != nil {
		return nil, err
	}
	if err := os.MkdirAll(classes, 0o755); err != nil {
		return nil, err
	}
	if err := os.WriteFile(srcPath, []byte(tr.Source), 0o644); err != nil {
		return nil, err
	}
	cp := srcDir + string(os.PathListSeparator) + classpath
	expr := "(binding [*compile-path* " + cljString(classes) + "] (compile '" + tr.NS + "))"
	_, stderr, err := snipcore.Run(
		[]string{"java", "-cp", cp, "clojure.main", "-e", expr},
		nil, timeout)
	if err != nil {
		if _, ok := err.(*snipcore.TimeoutError); ok {
			return nil, fmt.Errorf("compile TIMEOUT (>%ds)", timeout)
		}
		return nil, fmt.Errorf("compile exit %d: %s", snipcore.ExitCode(err), lastLine(stderr))
	}
	if _, err := os.Stat(filepath.Join(classes, classFile(tr.Class))); err != nil {
		return nil, fmt.Errorf("no class file after compile: %s", lastLine(stderr))
	}
	if err := os.WriteFile(marker, []byte(wantMarker), 0o644); err != nil {
		return nil, err
	}
	return &Built{NS: tr.NS, Class: tr.Class, ClassesDir: classes}, nil
}

// classFile maps a binary class name to its .class path.
func classFile(class string) string {
	return filepath.Join(strings.Split(class, ".")...) + ".class"
}

func lastLine(stderr []byte) string {
	text := strings.TrimSpace(string(stderr))
	if text == "" {
		return "no stderr"
	}
	lines := strings.Split(text, "\n")
	return strings.TrimSpace(lines[len(lines)-1])
}
