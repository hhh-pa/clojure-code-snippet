#!/usr/bin/env python3
"""CodSpeed benchmark inputs and configuration for the Clojure snippets.

CodSpeed measures each snippet end to end through the CodSpeed CLI
(`codspeed run -m walltime`, driven by `codspeed.yml` at the repository
root). Inputs come from the deterministic slope generators in
tools/generators (stdlib-only, fixed seed), so the benchmarks need neither
the encrypted test bundle nor any secret.

Each benchmark runs one snippet once on the smallest calibrated slope
scale of its generator (`scales[0]`, seed 1000): large enough for the
solve to dominate JVM startup, small enough to keep a full CI pass short.

Subcommands:

    python3 bench/codspeed_bench.py prepare [--check] [--only substr]
        Write bench/inputs/<key>.in (and .expected). With --check, run
        every snippet once and diff stdout against the expected output
        (same normalization as tests/run_tests.py), printing wall times.

    python3 bench/codspeed_bench.py config
        Regenerate codspeed.yml from the generator registry. Run it after
        adding or removing a generator, then commit the result.

The benchmark command itself is bench/run.sh <key> <script>.
"""

import argparse
import os
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INPUTS = os.path.join(ROOT, "bench", "inputs")
CONFIG = os.path.join(ROOT, "codspeed.yml")
SEED = 1000

sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "tests"))


def benchmarks(only=""):
    """Return sorted [(name, key, script_rel, generator, n)]."""
    import generators

    out = []
    for name, gen in sorted(generators.GENERATORS.items()):
        if only and only not in name:
            continue
        label, _, stem = name.rpartition("/")
        script = os.path.join("src", label, stem + ".clj")
        if not os.path.isfile(os.path.join(ROOT, script)):
            # compiler/* snippets live directly under src/compiler/ and
            # their registry names double the stem.
            area = label.split("/", 1)[0]
            script = os.path.join("src", area, stem + ".clj")
        if not os.path.isfile(os.path.join(ROOT, script)):
            raise SystemExit("no script for generator {}".format(name))
        key = name.replace("/", "__")
        out.append((name, key, script, gen, gen.scales[0]))
    return out


def prepare(only, check, timeout):
    from run_tests import normalize, resolve_classpath

    os.makedirs(INPUTS, exist_ok=True)
    classpath = resolve_classpath(None) if check else None
    failures = []
    for name, key, script, gen, n in benchmarks(only):
        data_in, data_out, _ = gen.generate(n, seed=SEED)
        in_path = os.path.join(INPUTS, key + ".in")
        with open(in_path, "wb") as fd:
            fd.write(data_in)
        with open(os.path.join(INPUTS, key + ".expected"), "wb") as fd:
            fd.write(data_out)
        if not check:
            print("generated {} (n={})".format(name, n), flush=True)
            continue
        start = time.time()
        with open(in_path, "rb") as fd:
            try:
                proc = subprocess.run(
                    ["java", "-cp", classpath, "clojure.main",
                     os.path.join(ROOT, script)],
                    stdin=fd, stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE, timeout=timeout)
                ok = (proc.returncode == 0
                      and normalize(proc.stdout) == normalize(data_out))
            except subprocess.TimeoutExpired:
                ok = False
        elapsed = time.time() - start
        status = "ok" if ok else "FAIL"
        print("{:5} {:7.2f}s {} (n={})".format(status, elapsed, name, n),
              flush=True)
        if not ok:
            failures.append(name)
    if failures:
        print("failed: " + ", ".join(failures), file=sys.stderr)
        return 1
    return 0


def write_config():
    lines = [
        "$schema: https://raw.githubusercontent.com/CodSpeedHQ/codspeed/"
        "refs/heads/main/schemas/codspeed.schema.json",
        "",
        "# Generated by `python3 bench/codspeed_bench.py config`; do not edit",
        "# by hand. Inputs are produced by `bench/codspeed_bench.py prepare`.",
        "# Each benchmark runs one snippet end to end on the JVM (startup",
        "# included) on the smallest calibrated slope scale of its generator.",
        "",
        "options:",
        "  warmup-time: 1s",
        "  max-time: 4s",
        "  max-rounds: 5",
        "",
        "benchmarks:",
    ]
    for name, key, script, _, n in benchmarks():
        lines.append("  - name: {}".format(name))
        lines.append("    exec: bench/run.sh {} {}".format(key, script))
    with open(CONFIG, "w") as fd:
        fd.write("\n".join(lines) + "\n")
    print("wrote {}".format(os.path.relpath(CONFIG, ROOT)))
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    prep = sub.add_parser("prepare", help="generate benchmark inputs")
    prep.add_argument("--only", default="", help="substring filter")
    prep.add_argument("--check", action="store_true",
                      help="run each snippet once and verify its output")
    prep.add_argument("--timeout", type=int, default=300)
    sub.add_parser("config", help="regenerate codspeed.yml")
    args = parser.parse_args(argv)
    if args.cmd == "prepare":
        return prepare(args.only, args.check, args.timeout)
    return write_config()


if __name__ == "__main__":
    sys.exit(main())
